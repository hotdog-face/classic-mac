#!/usr/bin/env python3
"""
extract_cart.py -- pull the binary data sections out of a PICO-8 .p8 cartridge
and emit C headers the Mac Classic port can compile directly.

PICO-8 stores its non-code data as text sections at the end of the .p8 file:

  __gfx__   128 rows x 128 hex nibbles   -> the 128x128 sprite sheet (each
                                            nibble is one pixel, palette index 0-15)
  __gff__   2 rows x 256 hex chars       -> 256 sprite *flag* bytes.  This game
                                            (over)loads these as per-entity-class
                                            metadata; 6 bytes per entity class.
  __map__   32 rows x 256 hex chars      -> the 128x32 tile map (bytes = sprite ids)
                                            (only the top-left 16x16 is used here)

We deliberately do NOT try to parse __sfx__/__music__ yet -- PICO-8 audio is
procedurally synthesised and is a separate port phase.  We dump them raw so the
audio work later has the data on hand.

Usage:  python3 extract_cart.py source/just_one_boss.p8 src/generated
"""
import sys, os, textwrap

def read_sections(path):
    """Return {section_name: [line, line, ...]} for every __name__ block."""
    sections, current = {}, None
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("__") and line.endswith("__"):
                current = line.strip("_")
                sections[current] = []
            elif current is not None:
                sections[current].append(line)
    return sections

def hexnibbles(lines, expect_rows):
    """Each char is one 4-bit value. Returns a flat list of ints."""
    out = []
    for row in lines:
        row = row.strip()
        if not row:
            continue
        for ch in row:
            out.append(int(ch, 16))
    return out

def hexbytes(lines):
    """Each pair of chars is one byte. Returns a flat list of ints."""
    out = []
    for row in lines:
        row = row.strip()
        for i in range(0, len(row) - 1, 2):
            out.append(int(row[i:i+2], 16))
    return out

def c_array(name, values, per_row, ctype="unsigned char"):
    body = ""
    for i in range(0, len(values), per_row):
        chunk = ",".join(str(v) for v in values[i:i+per_row])
        body += "    " + chunk + ",\n"
    return f"const {ctype} {name}[{len(values)}] = {{\n{body}}};\n"

def main():
    if len(sys.argv) < 3:
        print(__doc__)
        sys.exit(1)
    cart, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)
    sec = read_sections(cart)

    # --- sprite sheet: 128x128 palette indices (one byte per pixel) ---
    gfx = hexnibbles(sec.get("gfx", []), 128)
    # pad/truncate to exactly 128*128
    gfx = (gfx + [0] * (128 * 128))[:128 * 128]
    with open(os.path.join(outdir, "gfx_data.h"), "w") as f:
        f.write("/* auto-generated by tools/extract_cart.py -- do not edit */\n")
        f.write("#ifndef GFX_DATA_H\n#define GFX_DATA_H\n")
        f.write("#define GFX_W 128\n#define GFX_H 128\n")
        f.write("/* one byte per pixel, value = PICO-8 palette index 0..15 */\n")
        f.write("extern const unsigned char gfx_data[128*128];\n#endif\n")
    with open(os.path.join(outdir, "gfx_data.c"), "w") as f:
        f.write('/* auto-generated by tools/extract_cart.py -- do not edit */\n')
        f.write('#include "gfx_data.h"\n')
        f.write(c_array("gfx_data", gfx, 32))

    # --- sprite flags: 256 bytes, used as entity-class metadata (6 per class) ---
    flags = hexbytes(sec.get("gff", []))
    flags = (flags + [0] * 256)[:256]
    with open(os.path.join(outdir, "sprite_flags.h"), "w") as f:
        f.write("/* auto-generated by tools/extract_cart.py -- do not edit */\n")
        f.write("#ifndef SPRITE_FLAGS_H\n#define SPRITE_FLAGS_H\n")
        f.write("extern const unsigned char sprite_flags[256];\n#endif\n")
    with open(os.path.join(outdir, "sprite_flags.c"), "w") as f:
        f.write('/* auto-generated by tools/extract_cart.py -- do not edit */\n')
        f.write('#include "sprite_flags.h"\n')
        f.write(c_array("sprite_flags", flags, 16))

    # --- map: 128x32 tile ids (only 16x16 used, but store the full top block) ---
    mp = hexbytes(sec.get("map", []))
    mp = (mp + [0] * (128 * 32))[:128 * 32]
    with open(os.path.join(outdir, "map_data.h"), "w") as f:
        f.write("/* auto-generated by tools/extract_cart.py -- do not edit */\n")
        f.write("#ifndef MAP_DATA_H\n#define MAP_DATA_H\n")
        f.write("#define MAP_W 128\n#define MAP_H 32\n")
        f.write("extern const unsigned char map_data[128*32];\n#endif\n")
    with open(os.path.join(outdir, "map_data.c"), "w") as f:
        f.write('/* auto-generated by tools/extract_cart.py -- do not edit */\n')
        f.write('#include "map_data.h"\n')
        f.write(c_array("map_data", mp, 32))

    # --- raw audio dump for the later audio-port phase ---
    with open(os.path.join(outdir, "audio_raw.txt"), "w") as f:
        f.write("__sfx__\n" + "\n".join(sec.get("sfx", [])) + "\n")
        f.write("__music__\n" + "\n".join(sec.get("music", [])) + "\n")

    # --- report the decoded entity-class flag table (design aid, not compiled) ---
    print("Extracted:")
    print(f"  gfx  : {len(gfx)} pixels (128x128)")
    print(f"  flags: {len(flags)} bytes")
    print(f"  map  : {len(mp)} tiles")
    print()
    print("Entity-class flags (sid = 6*class-6): "
          "[layer, frames_to_death, boolbits, extends, hitbox_ch, hurtbox?]")
    for cls in range(1, 32):
        sid = 6 * cls - 6
        row = flags[sid:sid + 6]
        if any(row):
            b = row[2]
            print(f"  class {cls:2d}: layer={row[0]:3d} "
                  f"ttl={row[1]:3d} boss_gen={b & 1} pause_immune={(b>>1)&1} "
                  f"extends={row[3]} hitbox={row[4]} raw={row}")

if __name__ == "__main__":
    main()
