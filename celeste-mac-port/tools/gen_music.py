#!/usr/bin/env python3
"""
gen_music.py -- decode ccleste's music loops (mus0/10/20/30/40.ogg, the
PICO-8 soundtrack as rendered audio) into src/generated/music_data.c/h:
8-bit offset-binary mono at 5563 Hz (22254.5/4 -- a clean divisor of the
Mac's native rate, so Sound Manager upsampling is cheap and artifact-free).

Full track lengths are kept so loops are musically seamless (~1MB total;
the app needs a >=2MB Mac).  For a music-less "lite" build just rebuild
without regenerating this file's arrays (see PORTING-NOTES).

Requires ffmpeg on PATH.

Usage: python3 gen_music.py <ccleste_dir> <out_dir>
"""
import subprocess
import sys

TRACKS = [0, 10, 20, 30, 40]     # celeste music() indices; file = mus<i>.ogg
RATE = 5563


def decode(path):
    return subprocess.run(
        ['ffmpeg', '-v', 'quiet', '-i', path,
         '-ac', '1', '-ar', str(RATE), '-f', 'u8', '-'],
        check=True, capture_output=True).stdout


def main():
    src, out = sys.argv[1], sys.argv[2]
    blobs = {}
    total = 0
    for t in TRACKS:
        blobs[t] = decode(f'{src}/data/mus{t}.ogg')
        total += len(blobs[t])

    with open(f'{out}/music_data.h', 'w') as f:
        f.write('/* auto-generated by tools/gen_music.py -- do not edit */\n'
                '#ifndef MUSIC_DATA_H\n#define MUSIC_DATA_H\n'
                '/* 8-bit offset-binary mono loops @ 5563 Hz (22254.5/4) */\n'
                f'#define MUSIC_RATE_HZ {RATE}\n'
                '#define MUSIC_SLOTS 5   /* celeste index/10 */\n'
                'typedef struct { const unsigned char *data; long len; } MusicTrack;\n'
                'extern const MusicTrack music_table[MUSIC_SLOTS];\n'
                '#endif\n')
    with open(f'{out}/music_data.c', 'w') as f:
        f.write('/* auto-generated by tools/gen_music.py -- do not edit */\n'
                '#include "music_data.h"\n\n')
        for t in TRACKS:
            b = blobs[t]
            f.write(f'static const unsigned char mus{t}[{len(b)}] = {{\n')
            for o in range(0, len(b), 20):
                f.write(','.join(str(v) for v in b[o:o + 20]) + ',\n')
            f.write('};\n')
        f.write('\nconst MusicTrack music_table[MUSIC_SLOTS] = {\n')
        for t in TRACKS:
            f.write(f'    {{ mus{t}, {len(blobs[t])} }},\n')
        f.write('};\n')
    print(f'{len(TRACKS)} tracks, {total} bytes total '
          f'({total / 1024:.0f} KB @ {RATE} Hz)')


if __name__ == '__main__':
    main()
