#!/usr/bin/env python3
"""
gen_data.py -- generate src/generated/* for the Celeste Classic Mac port.

Inputs (from a ccleste checkout):
  data/gfx.bmp   128x64 4bpp indexed BMP of the PICO-8 sprite sheet
  tilemap.h      tilemap_data[8192] (128x64 tiles) + tile_flags[]

Outputs match the format the reused p8.c layer expects (same as the
Just One Boss port's extract_cart.py):
  gfx_data.c/h      unsigned char gfx_data[128*128], palette indices 0..15
                    (bottom half zero -- Celeste's sheet is 128x64)
  map_data.c/h      unsigned char map_data[128*64]  (MAP_H = 64: Celeste uses
                    the gfx-shared map rows, unlike JOB's 128x32)
  sprite_flags.c/h  unsigned char sprite_flags[256] (tile_flags padded)

Usage: python3 gen_data.py <ccleste_dir> <out_dir>
"""
import re
import struct
import sys

PICO8_PALETTE = [
    (0, 0, 0), (29, 43, 83), (126, 37, 83), (0, 135, 81),
    (171, 82, 54), (95, 87, 79), (194, 195, 199), (255, 241, 232),
    (255, 0, 77), (255, 163, 0), (255, 236, 39), (0, 228, 54),
    (41, 173, 255), (131, 118, 156), (255, 119, 168), (255, 204, 170),
]


def nearest_pico8(rgb):
    return min(range(16), key=lambda i: sum((a - b) ** 2 for a, b in zip(PICO8_PALETTE[i], rgb)))


def read_gfx_bmp(path):
    d = open(path, 'rb').read()
    data_ofs = struct.unpack('<I', d[10:14])[0]
    hdr_size = struct.unpack('<I', d[14:18])[0]
    w, h = struct.unpack('<ii', d[18:26])
    bpp = struct.unpack('<H', d[28:30])[0]
    assert bpp == 4, f'expected 4bpp BMP, got {bpp}'
    pal_ofs = 14 + hdr_size
    palette = []  # BMP palette entry -> pico8 index
    for i in range(16):
        b, g, r, _ = d[pal_ofs + i * 4: pal_ofs + i * 4 + 4]
        palette.append(nearest_pico8((r, g, b)))
    row_bytes = ((w * 4 + 31) // 32) * 4
    top_down = h < 0
    h = abs(h)
    px = [[0] * w for _ in range(h)]
    for y in range(h):
        src_y = y if top_down else h - 1 - y
        row = d[data_ofs + src_y * row_bytes: data_ofs + (src_y + 1) * row_bytes]
        for x in range(w):
            nyb = (row[x // 2] >> (4 if x % 2 == 0 else 0)) & 0xF
            px[y][x] = palette[nyb]
    return w, h, px


def parse_c_array(text, name):
    m = re.search(name + r"\s*\[[^\]]*\]\s*=\s*\{([^}]*)\}", text, re.S)
    assert m, f'array {name} not found'
    def c_int(t):  # match C literal rules: 0x.. hex, leading 0 octal, else decimal
        if t.lower().startswith('0x'):
            return int(t, 16)
        if len(t) > 1 and t[0] == '0':
            return int(t, 8)
        return int(t)
    return [c_int(t) for t in re.findall(r'0[xX][0-9a-fA-F]+|\d+', m.group(1))]


def emit(out_dir, base, guard, decls, defs):
    with open(f'{out_dir}/{base}.h', 'w') as f:
        f.write('/* auto-generated by tools/gen_data.py -- do not edit */\n')
        f.write(f'#ifndef {guard}\n#define {guard}\n{decls}#endif\n')
    with open(f'{out_dir}/{base}.c', 'w') as f:
        f.write('/* auto-generated by tools/gen_data.py -- do not edit */\n')
        f.write(f'#include "{base}.h"\n{defs}')


def emit_bytes(vals, per_line=16):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append(','.join(str(v) for v in vals[i:i + per_line]))
    return ',\n'.join(lines)


def main():
    src, out = sys.argv[1], sys.argv[2]
    w, h, px = read_gfx_bmp(f'{src}/data/gfx.bmp')
    assert (w, h) == (128, 64), f'unexpected gfx size {w}x{h}'
    gfx = [0] * (128 * 128)
    for y in range(h):
        for x in range(w):
            gfx[y * 128 + x] = px[y][x]

    tm = open(f'{src}/tilemap.h').read()
    tilemap = parse_c_array(tm, 'tilemap_data')
    assert len(tilemap) == 128 * 64, f'tilemap len {len(tilemap)}'
    flags = parse_c_array(tm, 'tile_flags')
    flags += [0] * (256 - len(flags))

    emit(out, 'gfx_data', 'GFX_DATA_H',
         '#define GFX_W 128\n#define GFX_H 128\n'
         '/* one byte per pixel, value = PICO-8 palette index 0..15 */\n'
         'extern const unsigned char gfx_data[128*128];\n',
         'const unsigned char gfx_data[128*128] = {\n' + emit_bytes(gfx) + '\n};\n')
    emit(out, 'map_data', 'MAP_DATA_H',
         '#define MAP_W 128\n#define MAP_H 64\n'
         'extern const unsigned char map_data[128*64];\n',
         'const unsigned char map_data[128*64] = {\n' + emit_bytes(tilemap) + '\n};\n')
    emit(out, 'sprite_flags', 'SPRITE_FLAGS_H',
         'extern const unsigned char sprite_flags[256];\n',
         'const unsigned char sprite_flags[256] = {\n' + emit_bytes(flags) + '\n};\n')
    used = sorted(set(gfx))
    print(f'gfx 128x64 ok (indices used: {used}); map {len(tilemap)} tiles; '
          f'{sum(1 for f in flags if f)} flagged tiles')


if __name__ == '__main__':
    main()
